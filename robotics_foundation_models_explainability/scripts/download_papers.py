#!/usr/bin/env python3
"""Download the included arXiv papers to papers/ and extract their text, title-checked.

Reads lit_review/included.json (manual screening decisions). For every work with an arXiv id and
"download": true, it fetches the arXiv abs page, compares citation_title with the recorded title
(SequenceMatcher >= 0.85 on normalised text), and only then saves the PDF. Saved bytes must start
with %PDF and exceed 20 kB, so an error page cannot pass as a paper. Text goes to papers/text/<id>.txt
via pdftotext (poppler), for reading and for reference-list chaining (lit_refchain.py).

Resumable: existing PDFs that pass the magic-number check are kept. A title mismatch or failed
download is logged at ERROR, recorded in papers/manifest.json, and makes the script exit 1.

Usage (from robotics_foundation_models_explainability/), ~4 s per paper (3 s polite delay), so ~4 min for 60:
    .venv/Scripts/python.exe scripts/download_papers.py --dry-run   # title checks only
    .venv/Scripts/python.exe scripts/download_papers.py
"""

import argparse
import html
import json
import logging
import re
import subprocess
import sys
import time
import unicodedata
from difflib import SequenceMatcher
from pathlib import Path
from typing import Dict, Optional

import requests

ROOT = Path(__file__).resolve().parents[1]
INCLUDED = ROOT / "lit_review" / "included.json"
OUTDIR = ROOT / "papers"
TEXTDIR = OUTDIR / "text"
USER_AGENT = "robotics-fm-explainability-lit-review/1.0 (mailto:tarkhanyan02@gmail.com)"
TIMEOUT_S = 90
DELAY_S = 3.0
MAX_RETRIES = 4
TITLE_MATCH = 0.85
MIN_PDF_BYTES = 20_000


def setup_logging() -> None:
    (ROOT / "logs").mkdir(exist_ok=True)
    logging.basicConfig(
        level=logging.INFO, format="%(asctime)s %(levelname)-8s %(message)s",
        handlers=[logging.FileHandler(ROOT / "logs" / "download_papers.log", encoding="utf-8"),
                  logging.StreamHandler(sys.stdout)])


def norm(text: str) -> str:
    text = unicodedata.normalize("NFKD", (text or "").lower())
    return re.sub(r"[^a-z0-9]+", "", "".join(c for c in text if not unicodedata.combining(c)))


def get(url: str) -> requests.Response:
    for attempt in range(1, MAX_RETRIES + 1):
        try:
            r = requests.get(url, timeout=TIMEOUT_S, headers={"User-Agent": USER_AGENT})
        except requests.RequestException as exc:
            logging.warning(f"request error {url} (attempt {attempt}): {exc}")
            time.sleep(5.0 * attempt)
            continue
        if r.status_code == 200:
            return r
        if r.status_code in (429, 500, 502, 503, 504):
            wait = 10.0 * 2 ** attempt
            logging.warning(f"HTTP {r.status_code} for {url} (attempt {attempt}/{MAX_RETRIES}), retry in {wait:.0f}s")
            time.sleep(wait)
            continue
        r.raise_for_status()
    raise RuntimeError(f"failed after {MAX_RETRIES} attempts: {url}")


def abs_title(arxiv_id: str) -> str:
    page = get(f"https://arxiv.org/abs/{arxiv_id}").text
    m = re.search(r'name=["\']citation_title["\'][^>]+content=["\']([^"\']+)', page)
    if not m:
        raise RuntimeError(f"no citation_title on abs page for {arxiv_id}")
    return " ".join(html.unescape(m.group(1)).split())


def is_pdf(path: Path) -> bool:
    return path.exists() and path.stat().st_size > MIN_PDF_BYTES and path.read_bytes()[:4] == b"%PDF"


def extract_text(pdf: Path, txt: Path) -> int:
    subprocess.run(["pdftotext", "-enc", "UTF-8", str(pdf), str(txt)], check=True)
    return len(txt.read_text(encoding="utf-8", errors="replace"))


def write_list(manifest: Dict[str, Dict]) -> None:
    """papers/README.md: the collection as a table with arXiv links, so it survives the PDFs being gitignored."""
    rows = sorted(((aid, m) for aid, m in manifest.items() if m.get("status") == "ok"),
                  key=lambda kv: (kv[1]["tier"] != "core", kv[1]["section"], kv[0]))
    total_mb = sum(m.get("bytes", 0) for _, m in rows) / 1e6
    lines = ["# Paper collection", "",
             f"{len(rows)} arXiv papers included in the review, {total_mb:.0f} MB of PDFs. The PDFs are gitignored; "
             "rebuild them with `.venv/Scripts/python.exe scripts/download_papers.py` (title-checked against arXiv, "
             "resumable). Extracted text is in `text/`, full metadata in `manifest.json`. Generated by "
             "`download_papers.py`; do not edit by hand.", "",
             "| arXiv id | Title | Section | Tier | Links |", "|---|---|---|---|---|"]
    for aid, m in rows:
        title = m["title"].replace("|", "/")
        lines.append(f"| {aid} | {title} | {m['section']} | {m['tier']} | "
                     f"[abs]({m.get('abs_url', f'https://arxiv.org/abs/{aid}')}) "
                     f"[pdf]({m.get('pdf_url', f'https://arxiv.org/pdf/{aid}')}) |")
    (OUTDIR / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry-run", action="store_true", help="check titles, download nothing")
    args = ap.parse_args()
    setup_logging()
    start = time.time()
    OUTDIR.mkdir(exist_ok=True)
    TEXTDIR.mkdir(exist_ok=True)
    works = [w for w in json.loads(INCLUDED.read_text(encoding="utf-8"))["works"]
             if w.get("arxiv_id") and w.get("download")]
    manifest_path = OUTDIR / "manifest.json"
    manifest: Dict[str, Dict] = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {}
    failures = []
    for i, w in enumerate(works, 1):
        aid = w["arxiv_id"]
        pdf = OUTDIR / f"{aid}.pdf"
        txt = TEXTDIR / f"{aid}.txt"
        entry: Optional[Dict] = manifest.get(aid)
        if entry and entry.get("status") == "ok" and is_pdf(pdf) and txt.exists():
            entry.update(key=w["key"], tier=w["tier"], section=w["section"],  # keep in step with included.json
                         abs_url=f"https://arxiv.org/abs/{aid}", pdf_url=f"https://arxiv.org/pdf/{aid}")
            logging.info(f"[{i}/{len(works)}] {aid} already downloaded")
            continue
        try:
            got = abs_title(aid)
            ratio = SequenceMatcher(None, norm(w["title"]), norm(got)).ratio()
            if ratio < TITLE_MATCH:
                raise RuntimeError(f"title mismatch (ratio {ratio:.2f}): included.json has {w['title']!r}, "
                                   f"arXiv has {got!r}")
            time.sleep(DELAY_S)
            if args.dry_run:
                logging.info(f"[{i}/{len(works)}] {aid} title OK ({ratio:.2f})")
                continue
            if not is_pdf(pdf):
                body = get(f"https://arxiv.org/pdf/{aid}").content
                if not body.startswith(b"%PDF") or len(body) < MIN_PDF_BYTES:
                    raise RuntimeError(f"response is not a PDF ({len(body)} bytes, starts {body[:8]!r})")
                pdf.write_bytes(body)
                time.sleep(DELAY_S)
            chars = extract_text(pdf, txt)
            manifest[aid] = {"status": "ok", "title": got, "key": w["key"], "tier": w["tier"],
                             "section": w["section"], "abs_url": f"https://arxiv.org/abs/{aid}",
                             "pdf_url": f"https://arxiv.org/pdf/{aid}", "title_match": round(ratio, 3),
                             "bytes": pdf.stat().st_size, "text_chars": chars,
                             "retrieved": time.strftime("%Y-%m-%d")}
            elapsed = time.time() - start
            logging.info(f"[{i}/{len(works)}] {aid} saved ({pdf.stat().st_size / 1e6:.1f} MB, {chars} chars), "
                         f"{elapsed:.0f}s elapsed, ~{elapsed / i * (len(works) - i):.0f}s left")
        except (RuntimeError, requests.RequestException, subprocess.CalledProcessError) as exc:
            logging.error(f"[{i}/{len(works)}] {aid} FAILED: {exc}")
            manifest[aid] = {"status": "failed", "title": w["title"], "error": str(exc)}
            failures.append(aid)
        manifest_path.write_text(json.dumps(manifest, indent=1, ensure_ascii=False), encoding="utf-8")
    manifest_path.write_text(json.dumps(manifest, indent=1, ensure_ascii=False), encoding="utf-8")
    write_list(manifest)
    ok = sum(1 for m in manifest.values() if m.get("status") == "ok")
    logging.info(f"Done in {time.time() - start:.0f}s: {ok} papers ok, {len(failures)} failed {failures}")
    if failures:
        sys.exit(1)


if __name__ == "__main__":
    main()
